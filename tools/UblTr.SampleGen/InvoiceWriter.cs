using System.Globalization;
using System.Text;
using System.Xml;
using System.Xml.Linq;
using UblTr.Validator;

namespace UblTr.SampleGen;

/// <summary>Writes an <see cref="InvoiceSpec"/> as UBL-TR 1.2.1 XML in schema order, with all totals computed.</summary>
public static class InvoiceWriter
{
    private static readonly XNamespace Cac = Ns.Cac;
    private static readonly XNamespace Cbc = Ns.Cbc;
    private static readonly XNamespace Ext = Ns.Ext;
    private static readonly XNamespace Xsi = "http://www.w3.org/2001/XMLSchema-instance";
    private static readonly XNamespace Synthetic = "urn:ubltr-validator:synthetic";

    public static XDocument ToXml(InvoiceSpec spec)
    {
        var cur = spec.Currency;
        var lines = spec.Lines.Select((l, i) => Compute(l, i + 1, spec)).ToList();
        var lineExtension = lines.Sum(l => l.Extension);
        var vatGroups = lines.GroupBy(l => l.Spec.VatPercent).OrderByDescending(g => g.Key)
            .Select(g => (Percent: g.Key, Taxable: g.Sum(l => l.Extension), Tax: g.Sum(l => l.Vat))).ToList();
        var vatTotal = vatGroups.Sum(g => g.Tax);
        var withheld = spec.Withholding is { } w ? Round(vatTotal * w.Percent / 100m) : 0m;
        var taxInclusive = lineExtension + vatTotal;

        var root = new XElement(Ns.Invoice + "Invoice",
            new XAttribute(XNamespace.Xmlns + "cac", Cac),
            new XAttribute(XNamespace.Xmlns + "cbc", Cbc),
            new XAttribute(XNamespace.Xmlns + "ext", Ext),
            new XAttribute(XNamespace.Xmlns + "xsi", Xsi),
            new XElement(Ext + "UBLExtensions",
                new XElement(Ext + "UBLExtension",
                    new XElement(Ext + "ExtensionContent",
                        // A real e-Fatura carries the XAdES signature here; synthetic samples are deliberately unsigned.
                        new XElement(Synthetic + "Unsigned", new XAttribute(XNamespace.Xmlns + "syn", Synthetic),
                            "Synthetic sample generated by ubltr-validator; not signed, not a real invoice.")))),
            new XElement(Cbc + "UBLVersionID", "2.1"),
            new XElement(Cbc + "CustomizationID", "TR1.2"),
            new XElement(Cbc + "ProfileID", spec.Profile),
            new XElement(Cbc + "ID", spec.Id),
            new XElement(Cbc + "CopyIndicator", "false"),
            new XElement(Cbc + "UUID", spec.Uuid.ToString()),
            new XElement(Cbc + "IssueDate", spec.IssueDate.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture)),
            new XElement(Cbc + "IssueTime", "10:15:00"),
            new XElement(Cbc + "InvoiceTypeCode", spec.Type),
            spec.Note is null ? null : new XElement(Cbc + "Note", spec.Note),
            new XElement(Cbc + "DocumentCurrencyCode", cur),
            new XElement(Cbc + "LineCountNumeric", lines.Count),
            spec.ReturnedInvoiceId is null ? null : new XElement(Cac + "BillingReference",
                new XElement(Cac + "InvoiceDocumentReference",
                    new XElement(Cbc + "ID", spec.ReturnedInvoiceId),
                    new XElement(Cbc + "IssueDate", spec.IssueDate.AddDays(-10).ToString("yyyy-MM-dd", CultureInfo.InvariantCulture)),
                    new XElement(Cbc + "DocumentTypeCode", "IADE"))),
            Signature(spec.Supplier),
            new XElement(Cac + "AccountingSupplierParty", Party(spec.Supplier)),
            new XElement(Cac + "AccountingCustomerParty", Party(spec.Customer)),
            spec.Currency == "TRY" || spec.ExchangeRate is null ? null : new XElement(Cac + "PricingExchangeRate",
                new XElement(Cbc + "SourceCurrencyCode", cur),
                new XElement(Cbc + "TargetCurrencyCode", "TRY"),
                new XElement(Cbc + "CalculationRate", spec.ExchangeRate.Value.ToString("0.######", CultureInfo.InvariantCulture)),
                new XElement(Cbc + "Date", spec.IssueDate.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture))),
            new XElement(Cac + "TaxTotal",
                Amount("TaxAmount", vatTotal, cur),
                vatGroups.Select(g => Subtotal(g.Taxable, g.Tax, g.Percent, cur, spec.Exemption))),
            spec.Withholding is null ? null : new XElement(Cac + "WithholdingTaxTotal",
                Amount("TaxAmount", withheld, cur),
                new XElement(Cac + "TaxSubtotal",
                    Amount("TaxableAmount", vatTotal, cur),
                    Amount("TaxAmount", withheld, cur),
                    new XElement(Cbc + "Percent", spec.Withholding.Percent.ToString("0.##", CultureInfo.InvariantCulture)),
                    new XElement(Cac + "TaxCategory",
                        new XElement(Cac + "TaxScheme",
                            new XElement(Cbc + "Name", "KDV Tevkifatı"),
                            new XElement(Cbc + "TaxTypeCode", spec.Withholding.Code))))),
            new XElement(Cac + "LegalMonetaryTotal",
                Amount("LineExtensionAmount", lineExtension, cur),
                Amount("TaxExclusiveAmount", lineExtension, cur),
                Amount("TaxInclusiveAmount", taxInclusive, cur),
                Amount("PayableAmount", taxInclusive - withheld, cur)),
            lines.Select(l => Line(l, spec)));

        return new XDocument(new XDeclaration("1.0", "UTF-8", null), root);
    }

    public static string ToXmlString(InvoiceSpec spec) => Serialize(ToXml(spec));

    public static string Serialize(XDocument document)
    {
        var settings = new XmlWriterSettings { Indent = true, IndentChars = "  ", Encoding = new UTF8Encoding(false), NewLineChars = "\n" };
        using var stream = new MemoryStream();
        using (var writer = XmlWriter.Create(stream, settings))
        {
            document.Save(writer);
        }

        return Encoding.UTF8.GetString(stream.ToArray()) + "\n";
    }

    private sealed record ComputedLine(LineSpec Spec, int Number, decimal Extension, decimal Vat);

    private static ComputedLine Compute(LineSpec line, int number, InvoiceSpec spec)
    {
        var extension = Round(line.Quantity * line.Price - line.Allowance);
        var vat = spec.Exemption is null ? Round(extension * line.VatPercent / 100m) : 0m;
        return new ComputedLine(line, number, extension, vat);
    }

    private static XElement Line(ComputedLine line, InvoiceSpec spec)
    {
        var cur = spec.Currency;
        return new XElement(Cac + "InvoiceLine",
            new XElement(Cbc + "ID", line.Number),
            new XElement(Cbc + "InvoicedQuantity", new XAttribute("unitCode", line.Spec.UnitCode),
                line.Spec.Quantity.ToString("0.###", CultureInfo.InvariantCulture)),
            Amount("LineExtensionAmount", line.Extension, cur),
            line.Spec.Allowance == 0m ? null : new XElement(Cac + "AllowanceCharge",
                new XElement(Cbc + "ChargeIndicator", "false"),
                new XElement(Cbc + "AllowanceChargeReason", "İskonto"),
                Amount("Amount", line.Spec.Allowance, cur),
                Amount("BaseAmount", Round(line.Spec.Quantity * line.Spec.Price), cur)),
            spec.LineTaxTotals ? new XElement(Cac + "TaxTotal",
                Amount("TaxAmount", line.Vat, cur),
                Subtotal(line.Extension, line.Vat, spec.Exemption is null ? line.Spec.VatPercent : 0m, cur, spec.Exemption)) : null,
            new XElement(Cac + "Item", new XElement(Cbc + "Name", line.Spec.Name)),
            new XElement(Cac + "Price", Amount("PriceAmount", line.Spec.Price, cur, priceFormat: true)));
    }

    private static XElement Subtotal(decimal taxable, decimal tax, decimal percent, string cur, ExemptionSpec? exemption) =>
        new(Cac + "TaxSubtotal",
            Amount("TaxableAmount", taxable, cur),
            Amount("TaxAmount", tax, cur),
            new XElement(Cbc + "Percent", (exemption is null ? percent : 0m).ToString("0.##", CultureInfo.InvariantCulture)),
            new XElement(Cac + "TaxCategory",
                exemption is null ? null : new XElement(Cbc + "TaxExemptionReasonCode", exemption.Code),
                exemption is null ? null : new XElement(Cbc + "TaxExemptionReason", exemption.Reason),
                new XElement(Cac + "TaxScheme",
                    new XElement(Cbc + "Name", "KDV"),
                    new XElement(Cbc + "TaxTypeCode", "0015"))));

    private static XElement Party(PartySpec party) =>
        new(Cac + "Party",
            new XElement(Cac + "PartyIdentification", new XElement(Cbc + "ID", new XAttribute("schemeID", party.Scheme), party.TaxId)),
            party.Name is null ? null : new XElement(Cac + "PartyName", new XElement(Cbc + "Name", party.Name)),
            new XElement(Cac + "PostalAddress",
                new XElement(Cbc + "StreetName", party.Street),
                new XElement(Cbc + "CitySubdivisionName", party.District),
                new XElement(Cbc + "CityName", party.City),
                new XElement(Cac + "Country", new XElement(Cbc + "IdentificationCode", "TR"), new XElement(Cbc + "Name", "Türkiye"))),
            new XElement(Cac + "PartyTaxScheme", new XElement(Cac + "TaxScheme", new XElement(Cbc + "Name", party.TaxOffice))),
            party.FirstName is null ? null : new XElement(Cac + "Person",
                new XElement(Cbc + "FirstName", party.FirstName),
                new XElement(Cbc + "FamilyName", party.FamilyName)));

    private static XElement Signature(PartySpec supplier) =>
        new(Cac + "Signature",
            new XElement(Cbc + "ID", new XAttribute("schemeID", "VKN_TCKN"), supplier.TaxId),
            new XElement(Cac + "SignatoryParty",
                new XElement(Cac + "PartyIdentification", new XElement(Cbc + "ID", new XAttribute("schemeID", supplier.Scheme), supplier.TaxId)),
                new XElement(Cac + "PostalAddress",
                    new XElement(Cbc + "CitySubdivisionName", supplier.District),
                    new XElement(Cbc + "CityName", supplier.City),
                    new XElement(Cac + "Country", new XElement(Cbc + "Name", "Türkiye")))),
            new XElement(Cac + "DigitalSignatureAttachment",
                new XElement(Cac + "ExternalReference", new XElement(Cbc + "URI", "#Signature_" + supplier.TaxId))));

    private static XElement Amount(string name, decimal value, string currency, bool priceFormat = false) =>
        new(Cbc + name, new XAttribute("currencyID", currency),
            value.ToString(priceFormat ? "0.00######" : "0.00", CultureInfo.InvariantCulture));

    private static decimal Round(decimal value) => Math.Round(value, 2, MidpointRounding.AwayFromZero);
}
